CREATE TABLE tasks (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamptz DEFAULT now(),
    planned_to timestamptz NOT NULL,
    started_at timestamptz,
    finished_at timestamptz,
    execution_count int DEFAULT 0,
    comment TEXT
);
CREATE INDEX tasks_created_at ON tasks(created_at);

CREATE TYPE _tasks_names AS (
    acquire text,
    finish text,
    retry text,
    reset text,
    clean text
);

CREATE FUNCTION _fill_tasks_names(table_name text)
RETURNS _tasks_names
LANGUAGE sql AS $$
    SELECT
        'acquire_' || table_name,
        'finish_' || table_name,
        'retry_' || table_name,
        'reset_' || table_name,
        'clean_' || table_name;
$$;


CREATE OR REPLACE FUNCTION register_task(
    schema_name text,
    table_name text,
    timeout interval,
    max_retries int
) RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    sql text;
    task_names_ _tasks_names := _fill_tasks_names(table_name);
BEGIN
    PERFORM unregister_task(schema_name, table_name);

    -- Acquire tasks
    sql := format(
        $FUNC$
            CREATE OR REPLACE FUNCTION
            %1$s.%2$s(max_num int)
            RETURNS SETOF %1$s.%3$s
            LANGUAGE sql VOLATILE AS $QUERY$
                UPDATE %1$I.%3$I
                SET
                    execution_count = execution_count + 1,
                    started_at = now()
                FROM (
                    SELECT id
                    FROM %1$I.%3$I
                    WHERE
                        finished_at IS NULL AND
                        execution_count < %4$s AND
                        planned_to <= now() AND (
                            started_at IS NULL OR now() - started_at > %5$L
                        )
                    ORDER BY created_at DESC
                    LIMIT max_num
                    FOR UPDATE SKIP LOCKED
                ) as acquired_tasks
                WHERE %1$I.%3$I.id = acquired_tasks.id
                RETURNING %1$I.%3$I.*
            $QUERY$;
        $FUNC$,
        schema_name,
        task_names_.acquire,
        table_name,
        max_retries,
        timeout
    );
    RAISE NOTICE USING message = sql;
    EXECUTE sql;

    -- Finished tasks
    sql := format(
        $FUNC$
            CREATE OR REPLACE FUNCTION
            %1$s.%2$s(
                task_id int,
                task_started_at timestamptz,
                task_comment text DEFAULT NULL
            )
            RETURNS VOID
            LANGUAGE sql VOLATILE AS $QUERY$
                UPDATE %1$I.%3$I
                SET
                    finished_at = now(),
                    comment = task_comment,
                    started_at = task_started_at
                WHERE
                    finished_at IS NULL AND
                    id = task_id;
            $QUERY$;
        $FUNC$,
        schema_name,
        task_names_.finish,
        table_name
    );
    RAISE NOTICE USING message = sql;
    EXECUTE sql;

    -- Retry tasks
    sql := format(
        $FUNC$
            CREATE OR REPLACE FUNCTION
            %1$s.%2$s(
                task_id int,
                planned_to timestamptz DEFAULT NULL,
                comment text DEFAULT NULL
            ) RETURNS VOID
            LANGUAGE sql VOLATILE
            AS $QUERY$
                UPDATE %1$I.%3$I
                SET
                    started_at = NULL
                WHERE
                    finished_at IS NULL AND
                    id = task_id;
            $QUERY$;
        $FUNC$,
        schema_name,
        task_names_.retry,
        table_name
    );
    RAISE NOTICE USING message = sql;
    EXECUTE sql;

    -- Reset task
    sql := format(
        $FUNC$
            CREATE OR REPLACE FUNCTION %1$s.%2$s(task_id int)
            RETURNS VOID
            LANGUAGE sql VOLATILE AS $QUERY$
                UPDATE %1$I.%3$I
                SET
                    started_at = NULL,
                    finished_at = NULL,
                    execution_count = 0
                WHERE id = task_id;
            $QUERY$;
        $FUNC$,
        schema_name,
        task_names_.reset,
        table_name
    );
    RAISE NOTICE USING message = sql;
    EXECUTE sql;
    -- Clean tasks
    sql := format(
        $FUNC$
            CREATE OR REPLACE FUNCTION %1$s.%2$s(finished_after interval)
            RETURNS int
            LANGUAGE sql VOLATILE AS $QUERY$
                WITH deleted AS (
                    DELETE FROM %1$I.%3$I
                    WHERE now() - finished_at > finished_after
                    RETURNING id
                )
                    SELECT count(*) FROM deleted;
            $QUERY$;
        $FUNC$,
        schema_name,
        task_names_.clean,
        table_name
    );
    RAISE NOTICE USING message = sql;
    EXECUTE sql;
END
$$;


CREATE OR REPLACE FUNCTION unregister_task(
    schema_name text,
    table_name text
) RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    task_names_ _tasks_names := _fill_tasks_names(table_name);
BEGIN
    EXECUTE format(
        'DROP FUNCTION IF EXISTS %I.%I',
        schema_name,
        task_names_.acquire
    );
    EXECUTE format(
        'DROP FUNCTION IF EXISTS %I.%I',
        schema_name,
        task_names_.finish
    );
    EXECUTE format(
        'DROP FUNCTION IF EXISTS %I.%I',
        schema_name,
        task_names_.retry
    );
    EXECUTE format(
        'DROP FUNCTION IF EXISTS %I.%I',
        schema_name,
        task_names_.reset
    );
    EXECUTE format(
        'DROP FUNCTION IF EXISTS %I.%I',
        schema_name,
        task_names_.clean
    );
END
$$;
